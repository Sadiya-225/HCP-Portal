// Development bootstrap: prepares local env, optionally starts an embedded
// loopback-only PostgreSQL, applies migrations, then starts Next dev.
// Cross-platform: no shell-dependent commands. Never logs credentials.

import { existsSync } from "node:fs";
import { writeFile } from "node:fs/promises";
import path from "node:path";
import crypto from "node:crypto";
import { spawn } from "node:child_process";
import EmbeddedPostgres from "embedded-postgres";

const EMBEDDED_PORT = 54329;
const DATA_DIR = path.resolve(".data", "postgres");
const ENV_LOCAL = path.resolve(".env.local");
const REQUIRED_KEYS = [
  "DATABASE_URL",
  "DATABASE_MIGRATION_URL",
  "BETTER_AUTH_SECRET",
  "BETTER_AUTH_URL",
  "DEV_EMBEDDED_POSTGRES",
];

const randomSecret = (bytes) => crypto.randomBytes(bytes).toString("base64url");

// Load existing env files first (without overriding process env), then
// decide whether secure defaults must be generated.
function loadEnvFiles() {
  for (const file of [".env.local", ".env"]) {
    if (existsSync(file)) {
      process.loadEnvFile(file);
    }
  }
}

function missingKeys() {
  return REQUIRED_KEYS.filter((key) => !process.env[key]);
}

async function maybeGenerateEnv() {
  const missing = missingKeys();
  if (missing.length === 0) return;

  if (!existsSync(ENV_LOCAL) && missing.length === REQUIRED_KEYS.length) {
    const dbPassword = randomSecret(24);
    const contents = [
      "# Auto-generated by scripts/dev.mjs for local development.",
      "# Safe defaults only; do not commit (this file is gitignored).",
      "NEXT_TELEMETRY_DISABLED=1",
      "DEV_EMBEDDED_POSTGRES=true",
      `DATABASE_URL=postgresql://hcp_dev:${dbPassword}@127.0.0.1:${EMBEDDED_PORT}/hcp_portal`,
      `DATABASE_MIGRATION_URL=postgresql://hcp_dev:${dbPassword}@127.0.0.1:${EMBEDDED_PORT}/hcp_portal`,
      `BETTER_AUTH_SECRET=${randomSecret(32)}`,
      "BETTER_AUTH_URL=http://localhost:3000",
      "TRUSTED_ORIGINS=http://localhost:3000",
      "DB_POOL_MAX=10",
      "PASSWORD_RESET_ENABLED=false",
      "",
    ].join("\n");
    await writeFile(ENV_LOCAL, contents, { mode: 0o600 });
    console.log("Created .env.local with generated local development values");
    process.loadEnvFile(ENV_LOCAL);
    return;
  }

  // Partial configuration (or an incomplete .env.local): never mix
  // externally supplied values with generated ones, never overwrite.
  console.error(
    `Local environment is incomplete. Missing keys: ${missing.join(", ")}.\n` +
      `Add them to .env.local or delete .env.local to regenerate safe defaults.`,
  );
  process.exit(1);
}

function parseEmbeddedTarget() {
  const flag = process.env.DEV_EMBEDDED_POSTGRES;
  if (flag !== "true" && flag !== "false") {
    console.error("DEV_EMBEDDED_POSTGRES must be exactly 'true' or 'false'.");
    process.exit(1);
  }
  if (flag !== "true") return null;

  let url;
  try {
    url = new URL(process.env.DATABASE_URL);
  } catch {
    console.error("DATABASE_URL is not a valid URL.");
    process.exit(1);
  }
  const hostOk = url.hostname === "127.0.0.1" || url.hostname === "localhost";
  if (!hostOk || Number(url.port) !== EMBEDDED_PORT) {
    console.error(
      `Embedded development PostgreSQL requires DATABASE_URL host 127.0.0.1/localhost on port ${EMBEDDED_PORT}. ` +
        `Set DEV_EMBEDDED_POSTGRES=false to use an external database.`,
    );
    process.exit(1);
  }
  return {
    user: decodeURIComponent(url.username),
    password: decodeURIComponent(url.password),
    database: decodeURIComponent(url.pathname.replace(/^\//, "")),
  };
}

function run(command, args, env) {
  return new Promise((resolve, reject) => {
    const child = spawn(command, args, { stdio: "inherit", env });
    child.on("error", reject);
    child.on("exit", (code, signal) => {
      if (code === 0) resolve();
      else reject(new Error(`Command failed (code ${code ?? signal})`));
    });
  });
}

let embeddedPg;
let nextChild;
let stopping = false;

function waitForExit(child, timeoutMs) {
  return new Promise((resolve) => {
    if (child.exitCode !== null) return resolve(true);
    const timer = setTimeout(() => resolve(false), timeoutMs);
    child.once("exit", () => {
      clearTimeout(timer);
      resolve(true);
    });
  });
}

function runSilent(command, args) {
  return new Promise((resolve) => {
    const child = spawn(command, args, { stdio: "ignore" });
    child.on("error", () => resolve());
    child.on("exit", () => resolve());
  });
}

// Terminate the entire Next dev process tree, then return once it is gone.
async function stopNext() {
  const child = nextChild;
  nextChild = undefined;
  if (!child || child.exitCode !== null || child.pid === undefined) return;
  const pid = child.pid;
  if (process.platform === "win32") {
    // taskkill /t is the standard Windows process-tree primitive.
    await runSilent("taskkill", ["/pid", String(pid), "/t", "/f"]);
  } else {
    // Spawned detached, so the child owns a process group: signal the group.
    try {
      process.kill(-pid, "SIGTERM");
    } catch {
      /* process group already gone */
    }
    if (!(await waitForExit(child, 5000))) {
      try {
        process.kill(-pid, "SIGKILL");
      } catch {
        /* already gone */
      }
      await waitForExit(child, 2000);
    }
  }
}

async function stopEmbedded() {
  if (!embeddedPg) return;
  const instance = embeddedPg;
  embeddedPg = undefined;
  try {
    await instance.stop();
  } catch {
    /* best-effort shutdown */
  }
}

async function shutdown(code) {
  if (stopping) return;
  stopping = true;
  await stopNext();
  await stopEmbedded();
  process.exit(code);
}

async function main() {
  loadEnvFiles();
  await maybeGenerateEnv();

  const embedded = parseEmbeddedTarget();

  try {
    if (embedded) {
      embeddedPg = new EmbeddedPostgres({
        databaseDir: DATA_DIR,
        port: EMBEDDED_PORT,
        user: embedded.user,
        password: embedded.password,
        authMethod: "scram-sha-256",
        persistent: true,
        postgresFlags: ["-c", "listen_addresses=127.0.0.1"],
        onLog: () => {},
        onError: (e) =>
          console.error(
            "Embedded PostgreSQL error:",
            e instanceof Error ? e.message : "unknown error",
          ),
      });

      if (!existsSync(path.join(DATA_DIR, "PG_VERSION"))) {
        console.log("Initializing local development database cluster…");
        await embeddedPg.initialise();
      }
      console.log("Starting local development database…");
      await embeddedPg.start();
      try {
        await embeddedPg.createDatabase(embedded.database);
      } catch (err) {
        if (err?.code !== "42P04") throw err; // 42P04 = already exists
      }
    } else {
      console.log("Using external PostgreSQL from DATABASE_URL.");
    }

    console.log("Applying database migrations…");
    await run(process.execPath, ["scripts/migrate.mjs"], process.env);

    const nextBin = path.resolve("node_modules/next/dist/bin/next");
    nextChild = spawn(
      process.execPath,
      [nextBin, "dev", ...process.argv.slice(2)],
      {
        stdio: "inherit",
        env: process.env,
        // Own process group on POSIX so the whole dev tree can be signalled.
        detached: process.platform !== "win32",
      },
    );

    process.on("SIGINT", () => void shutdown(nextChild?.exitCode ?? 0));
    process.on("SIGTERM", () => void shutdown(nextChild?.exitCode ?? 0));
    nextChild.on("exit", (code) => void shutdown(code ?? 0));
    nextChild.on("error", () => void shutdown(1));
  } catch (err) {
    await stopNext();
    await stopEmbedded();
    throw err;
  }
}

main().catch(async (err) => {
  console.error(
    "Development startup failed:",
    err instanceof Error ? err.message : "unknown error",
  );
  await stopEmbedded();
  process.exit(1);
});
